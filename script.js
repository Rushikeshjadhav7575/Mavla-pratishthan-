/* =========================================================
   CHANGE LANGUAGE
========================================================= */

function changeLanguage(language) {

    const selectedLanguage =
        translations[language];

    if (!selectedLanguage) {
        return;
    }


    /* Change all elements */

    document
        .querySelectorAll("[data-i18n]")
        .forEach(function(element) {

            const key =
                element.getAttribute("data-i18n");

            if (
                selectedLanguage[key] !== undefined
            ) {

                element.textContent =
                    selectedLanguage[key];

            }

        });


    /* Change HTML language */

    document.documentElement.lang =
        language;


    /* Save language */

    localStorage.setItem(
        "mavlaLanguage",
        language
    );


    /* Change title */

    if (language === "mr") {

        document.title =
            "मावळा प्रतिष्ठान | धर्म • संस्कृती • एकता";

    }

    else if (language === "en") {

        document.title =
            "Mavla Pratishthan | Faith • Culture • Unity";

    }

    else {

        document.title =
            "मावळा प्रतिष्ठान | धर्म • संस्कृति • एकता";

    }

}


